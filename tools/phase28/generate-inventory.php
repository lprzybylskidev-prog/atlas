    public function prepReportMarkdown(): string
    {
        $inventory = $this->inventory();
        $totals = $inventory['totals'];

        if (! is_array($totals)) {
            throw new RuntimeException('Phase 28 inventory totals are invalid.');
        }

        $moduleDrift = $this->moduleDependencyDrift();
        $moduleDriftEdgeCount = array_sum(array_map(
            static fn (array $row): int => count($row['undeclared_imports']),
            $moduleDrift,
        ));
        $auditDynamicValues = array_values(array_filter(
            $this->auditMatrixSignals(),
            static fn (array $signal): bool => str_starts_with((string) $signal['value'], '$'),
        ));

        $lines = [
            '# Phase 28 prep report',
            '',
            '> Generated by `php tools/phase28/generate-inventory.php --prep-report-markdown`.',
            '',
            'This is the Phase 28 preparation report. It summarizes the current code state before foundation repair implementation starts. It is not a claim that Phase 28 repairs are complete.',
            '',
            '## Readiness',
            '',
            '| Area | Status |',
            '| --- | --- |',
            '| Phase 28 prep | `100%` |',
            '| Automated backend/runtime/audit inventory | `ready` |',
            '| Frontend product consistency review | `recorded in phase file` |',
            '| Phase 28 implementation | `0%` |',
            '| Next implementation package | `P28-W02A` architecture guard hardening |',
            '| First frontend repair package | `P28-W05A` UI contract and glossary foundation |',
            '',
            '## Current Scale',
            '',
            '| Signal | Count |',
            '| --- | ---: |',
