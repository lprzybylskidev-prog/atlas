            $moduleClass = $this->firstFile($root, '/Module\.php$/');
            $contents = $moduleClass === null ? '' : $this->read($moduleClass);
            $key = $this->matchString($contents, "/new ModuleKey\\('([^']+)'\\)/") ?? basename($root);
            $category = $this->matchString($contents, '/ModuleCategory::([A-Za-z]+)/') ?? 'Unknown';
            $provider = $this->matchString($contents, '/return\s+([A-Za-z0-9_]+)::class;\s*\}\s*public function supportsGlobalActivation/s') ?? '';
            $moduleFiles = $this->files($this->relative($root), 'php');
            $publicFiles = array_values(array_filter($moduleFiles, static fn (string $file): bool => str_contains($file, '/Application/Public/')));
            $publicPersistence = array_values(array_filter($publicFiles, static fn (string $file): bool => str_contains($file, '/Application/Public/Persistence/')));

            $modules[] = [
                'key' => $key,
                'path' => $this->relative($root),
                'category' => $category,
                'required_dependencies' => $this->dependencies($contents, 'requiredDependencies'),
                'optional_dependencies' => $this->dependencies($contents, 'optionalDependencies'),
                'provider' => $provider,
                'public_file_count' => count($publicFiles),
                'public_persistence_file_count' => count($publicPersistence),
                'actual_module_imports' => $this->actualModuleImports($moduleFiles, $root),
                'controllers' => $this->matchingFiles([$this->relative($root)], '/Controller\.php$/'),
                'commands' => $this->matchingFiles([$this->relative($root)], '/Command\.php$/'),
                'jobs' => $this->matchingFiles([$this->relative($root)], '/Job\.php$/'),
            ];
        }

        usort($modules, static fn (array $left, array $right): int => strcmp((string) $left['key'], (string) $right['key']));

        return $modules;
    }

    /**
     * @return list<array{module: string, undeclared_imports: list<string>}>
     */
    private function moduleDependencyDrift(): array
    {
        $drift = [];

        foreach ($this->modules() as $module) {
            $declared = [
                ...$module['required_dependencies'],
                ...$module['optional_dependencies'],
            ];
            $undeclared = [];

            foreach ($module['actual_module_imports'] as $import) {
                $parts = explode('\\', (string) $import);
                $importedModule = $this->camelToSnake((string) ($parts[1] ?? ''));

                if ($importedModule === '' || in_array($importedModule, $declared, true)) {
                    continue;
                }

                $undeclared[] = (string) $import;
            }

            if ($undeclared === []) {
                continue;
            }

            $drift[] = [
                'module' => (string) $module['key'],
                'undeclared_imports' => array_values(array_unique($undeclared)),
            ];
        }

        return $drift;
    }

    /**
     * @return array<string, mixed>
     */
    private function routes(): array
    {
        $routeFiles = $this->files('routes', 'php');
        $routes = [];
        $prefixCounts = [];

        foreach ($routeFiles as $file) {
            $contents = $this->read($this->root.'/'.$file);
            preg_match_all('/Route::(?:get|post|put|patch|delete)\([^;]+?->name\(([^)]+)\)/s', $contents, $matches, PREG_SET_ORDER);

            foreach ($matches as $match) {
                $name = trim($match[1]);
                $name = trim($name, "'\"");

                if ($name === '' || str_contains($name, '::')) {
                    continue;
                }

                $prefix = explode('.', $name)[0] ?: $name;
                $prefixCounts[$prefix] = ($prefixCounts[$prefix] ?? 0) + 1;
                $routes[] = [
                    'name' => $name,
                    'prefix' => $prefix,
                    'file' => $file,
                ];
            }
        }

        ksort($prefixCounts);

        return [
            'route_count' => count($routes),
            'app_owned_prefix_counts' => $prefixCounts,
            'routes' => $routes,
        ];
    }

    /**
     * @return list<array{surface: string, method: string, uri: string, name: string, action: string, inertia_pages: list<string>}>
     */
    private function frameworkRoutes(): array
    {
        $json = shell_exec('cd '.escapeshellarg($this->root).' && php artisan route:list --json 2>/dev/null');

        if (! is_string($json) || trim($json) === '') {
            throw new RuntimeException('Unable to read framework route list from artisan.');
        }

        $decoded = json_decode($json, true);

        if (! is_array($decoded)) {
            throw new RuntimeException('Unable to decode framework route list JSON.');
        }

        $routes = [];

        foreach ($decoded as $route) {
            if (! is_array($route)) {
                continue;
            }

            $action = $this->stringValue($route['action'] ?? '');
            $path = $this->stringValue($route['path'] ?? '');

            if (! str_starts_with($action, 'App\\') && ! str_starts_with($path, 'routes/')) {
                continue;
            }

            $uri = $this->stringValue($route['uri'] ?? '');

            $routes[] = [
                'surface' => $this->surfaceForUri($uri),
                'method' => $this->stringValue($route['method'] ?? ''),
                'uri' => $uri,
                'name' => $this->stringValue($route['name'] ?? 'unnamed'),
                'action' => $action,
                'inertia_pages' => $this->inertiaPagesForFrameworkRoute($action, $path),
            ];
        }

        usort($routes, static function (array $left, array $right): int {
            return [$left['surface'], $left['uri'], $left['method'], $left['name']]
                <=> [$right['surface'], $right['uri'], $right['method'], $right['name']];
        });

        return $routes;
    }

    /**
     * @return list<string>
     */
    private function inertiaPagesForFrameworkRoute(string $action, string $path): array
    {
        $files = [];

        if (str_starts_with($action, 'App\\')) {
            [$class, $method] = array_pad(explode('@', $action, 2), 2, '__invoke');
            $candidate = $this->root.'/'.str_replace('\\', '/', preg_replace('/^App\\\\/', 'app/', $class) ?? $class).'.php';

            if (is_file($candidate)) {
                return $this->inertiaPagesForPhpFile($candidate, $method);
            }
        }

        $routeLine = $this->lineNumberFromPath($path);
        $routePath = preg_replace('/:\d+$/', '', $path) ?? $path;

        if (str_starts_with($routePath, 'routes/') && is_file($this->root.'/'.$routePath)) {
            return $this->inertiaPagesForPhpFile($this->root.'/'.$routePath, null, $routeLine);
        }

        $pages = [];

        foreach (array_unique($files) as $file) {
            array_push($pages, ...$this->inertiaPagesForPhpFile($file));
        }

        sort($pages);

        return array_values(array_unique($pages));
    }

    /**
     * @return list<string>
     */
    private function inertiaPagesForPhpFile(string $file, ?string $method = null, ?int $line = null): array
    {
        $contents = $this->read($file);

        if ($method !== null) {
            $methodBody = $this->methodBody($contents, $method);

            if ($methodBody !== null) {
                $contents = $methodBody;
            }
        }

        if ($method === null && $line !== null) {
            $contents = $this->lineWindow($contents, $line);
        }

        preg_match_all('/Inertia::render\(\s*[\'"]([^\'"]+)[\'"]/', $contents, $matches);
        $pages = $matches[1] ?? [];
        sort($pages);

        return array_values(array_unique($pages));
    }

    private function methodBody(string $contents, string $method): ?string
    {
        if (preg_match('/function\s+'.preg_quote($method, '/').'\s*\([^)]*\)\s*(?::\s*[^{}]+)?\{/s', $contents, $match, PREG_OFFSET_CAPTURE) !== 1) {
            return null;
        }

        $start = ($match[0][1] ?? 0) + strlen($match[0][0]);
        $depth = 1;
        $length = strlen($contents);

        for ($index = $start; $index < $length; $index++) {
            if ($contents[$index] === '{') {
                $depth++;
            }

            if ($contents[$index] === '}') {
                $depth--;

                if ($depth === 0) {
                    return substr($contents, $start, $index - $start);
                }
            }
        }

        return null;
    }

    private function lineNumberFromPath(string $path): ?int
    {
        if (preg_match('/:(\d+)$/', $path, $match) !== 1) {
            return null;
        }

        return (int) $match[1];
    }

    private function lineWindow(string $contents, int $line): string
    {
        $lines = explode("\n", $contents);
        $start = max(0, $line - 1);
        $window = [];

        for ($index = $start; $index < min(count($lines), $start + 24); $index++) {
            if ($index > $start && preg_match('/^\s*Route::/', $lines[$index]) === 1) {
                break;
            }

            $window[] = $lines[$index];
        }

        return implode("\n", $window);
    }

    private function surfaceForUri(string $uri): string
    {
        if ($uri === 'health/live' || $uri === 'health/ready') {
