    /**
     * @return list<array{table: string, column: string, target: string, file: string, line: int}>
     */
    private function migrationForeignKeySignals(): array
    {
        $foreignKeys = [];

        foreach ($this->migrationBlocks() as $block) {
            $table = $this->resolveTableExpression($block['expression']);

            foreach ($block['lines'] as $lineOffset => $line) {
                if (preg_match('/\$table->foreignId\([\'"]([^\'"]+)[\'"]\)(?<tail>.*?);/', $line, $match) === 1) {
                    if (preg_match('/->constrained\((?<target>[^)]*)\)/', $match['tail'], $targetMatch) !== 1) {
                        continue;
                    }

                    $foreignKeys[] = [
                        'table' => $table,
                        'column' => $match[1],
                        'target' => $this->resolveTableExpression($targetMatch['target']),
                        'file' => $block['file'],
                        'line' => $block['line'] + $lineOffset,
                    ];
                }

                if (preg_match('/\$table->foreign\([\'"]([^\'"]+)[\'"]\)/', $line, $match) === 1) {
                    $joined = implode(' ', array_slice($block['lines'], $lineOffset, 4));
                    $target = 'unresolved';

                    if (preg_match('/->on\((?<target>[^)]*)\)/', $joined, $targetMatch) === 1) {
                        $target = $this->resolveTableExpression($targetMatch['target']);
                    }

                    $foreignKeys[] = [
                        'table' => $table,
                        'column' => $match[1],
                        'target' => $target,
                        'file' => $block['file'],
                        'line' => $block['line'] + $lineOffset,
                    ];
                }
            }
        }

        return $foreignKeys;
    }

    /**
     * @return list<array{operation: string, expression: string, file: string, line: int, lines: list<string>}>
     */
    private function migrationBlocks(): array
    {
        $blocks = [];

        foreach ($this->files('database/migrations', 'php') as $file) {
            $lines = explode("\n", $this->read($this->root.'/'.$file));
            $current = null;

            foreach ($lines as $index => $line) {
                if ($current === null && preg_match('/Schema::(create|table)\((?<expression>[^,]+),/', $line, $match) === 1) {
                    $current = [
                        'operation' => $match[1],
                        'expression' => $this->compactExpression($match['expression']),
                        'file' => $file,
                        'line' => $index + 1,
                        'lines' => [$line],
                    ];

                    continue;
                }

                if ($current === null) {
                    continue;
                }

                $current['lines'][] = $line;

                if (preg_match('/^\s*\}\);/', $line) === 1) {
                    $blocks[] = $current;
                    $current = null;
                }
            }
        }

        return $blocks;
    }

    private function resolveTableExpression(string $expression): string
    {
        $expression = $this->compactExpression($expression);

        if (preg_match('/^[\'"]([^\'"]+)[\'"]$/', $expression, $match) === 1) {
            return $match[1];
        }

        if (preg_match('/^([A-Za-z0-9_]+)::([A-Z0-9_]+)$/', $expression, $match) === 1) {
            $key = $match[1].'::'.$match[2];

            return $this->databaseTableConstants()[$key] ?? 'unresolved:'.$expression;
        }

        if (preg_match('/^DatabaseSchema::([A-Z0-9_]+)\.\'[.]([^\'"]+)\'$/', $expression, $match) === 1) {
            $schema = $this->databaseSchemaConstants()[$match[1]] ?? 'unresolved_schema:'.$match[1];

            return $schema.'.'.$match[2];
        }

        return 'unresolved:'.$expression;
    }

    /**
     * @return array<string, string>
     */
    private function databaseTableConstants(): array
    {
        $schemas = $this->databaseSchemaConstants();
        $constants = [];

        foreach ([...$this->files('app/Shared/Infrastructure/Database', 'php'), ...$this->matchingFiles(['app/Modules'], '#/Application/Public/Persistence/.*DatabaseTable\.php$#')] as $file) {
            $contents = $this->read($this->root.'/'.$file);

            if (preg_match('/final class ([A-Za-z0-9_]+)/', $contents, $classMatch) !== 1) {
                continue;
            }

            preg_match_all("/public const ([A-Z0-9_]+) = DatabaseSchema::([A-Z0-9_]+)\\.('[^']+');/", $contents, $matches, PREG_SET_ORDER);

            foreach ($matches as $match) {
                $schema = $schemas[$match[2]] ?? 'unresolved_schema:'.$match[2];
                $table = trim($match[3], "'");
                $constants[$classMatch[1].'::'.$match[1]] = $schema.$table;
            }
        }

        ksort($constants);

        return $constants;
    }

    /**
     * @return array<string, string>
     */
    private function databaseSchemaConstants(): array
    {
