    /**
     * @return list<array{table: string, column: string, type: string, file: string, line: int}>
     */
    private function migrationColumnSignals(): array
    {
        $columns = [];
        $nonColumns = [
            'foreign' => true,
            'index' => true,
            'primary' => true,
            'unique' => true,
        ];

        foreach ($this->migrationBlocks() as $block) {
            $table = $this->resolveTableExpression($block['expression']);

            foreach ($block['lines'] as $lineOffset => $line) {
                if (preg_match('/\$table->([A-Za-z][A-Za-z0-9_]*)\((?<args>[^;]*)\)/', $line, $match) !== 1) {
                    continue;
                }

                $type = $match[1];
                if (isset($nonColumns[$type])) {
                    continue;
                }

                $column = $this->firstStringArgument($match['args']) ?? $this->implicitColumnForBlueprintMethod($type);

                $columns[] = [
                    'table' => $table,
                    'column' => $column,
                    'type' => $type,
                    'file' => $block['file'],
                    'line' => $block['line'] + $lineOffset,
                ];
            }
        }

        return $columns;
    }

