            '/forceFill|DB::table|->insert\s*\(|->insertGetId\s*\(|->updateOrInsert\s*\(|Model::unguard|withoutEvents|Hash::make|assignRole|syncRoles|team_user|manager/',
        );
    }

    /**
     * @return list<array{file: string, line: int, match: string}>
     */
    private function runtimeSignals(): array
    {
        return $this->matchesInFiles(
            [
                ...$this->files('config', 'php'),
                ...$this->files('docker'),
                ...$this->files('.devcontainer'),
                ...$this->files('tools', 'sh', 'php', 'mjs'),
                ...$this->existingFiles([
                    '.dockerignore',
                    '.env.example',
                    'composer.json',
                    'package.json',
                    'playwright.config.ts',
                    'pnpm-lock.yaml',
                ]),
            ],
            '/DB_SEARCH_PATH|clamav|Horizon|queue:listen|queue:work|pnpm@latest|pnpm@|POSTGRES|PGDATA|chromium|playwright/i',
        );
    }

    /**
     * @return list<array{area: string, evidence: string, file: string, line: int, target: string}>
     */
    private function runtimeMatrixSignals(): array
    {
        $patterns = [
            ['area' => 'package_manager', 'pattern' => '/pnpm@latest|packageManager.*pnpm@/', 'target' => 'P28-RUNTIME-001/P28-RUNTIME-010'],
            ['area' => 'queue_worker', 'pattern' => '/queue:listen|queue:work|retry_after|timeout.*43200|--timeout=43200|--timeout=60/', 'target' => 'P28-RUNTIME-005'],
            ['area' => 'horizon', 'pattern' => '/Horizon|horizon|supervisor-1|maxProcesses|timeout.*43200/', 'target' => 'P28-RUNTIME-005'],
            ['area' => 'scheduler', 'pattern' => '/schedule:work|scheduler|SCHEDULER_HEARTBEAT/i', 'target' => 'P28-RUNTIME-006/P28-RUNTIME-007'],
            ['area' => 'database', 'pattern' => '/postgres:18|POSTGRES|PGDATA|DB_SEARCH_PATH|search_path/', 'target' => 'P28-RUNTIME-003/P28-RUNTIME-011'],
            ['area' => 'redis', 'pattern' => '/redis:8|REDIS_|redis-server|appendonly/', 'target' => 'P28-RUNTIME-003/P28-RUNTIME-005'],
            ['area' => 'search', 'pattern' => '/meilisearch|MEILI|SCOUT_DRIVER/', 'target' => 'P28-MOD-003/P28-RUNTIME-007'],
            ['area' => 'clamav', 'pattern' => '/clamav|ATLAS_FILES_SCANNER/i', 'target' => 'P28-RUNTIME-008'],
            ['area' => 'chromium_pdf', 'pattern' => '/chromium|playwright|PLAYWRIGHT_/', 'target' => 'P28-RUNTIME-009'],
            ['area' => 'network', 'pattern' => '/443:443|80:80|internal: true|network_mode: service:app/', 'target' => 'P28-RUNTIME-002'],
            ['area' => 'storage_backup', 'pattern' => '/app-storage|backup-data|backups|PGPASSWORD_FILE|backup/', 'target' => 'P28-RUNTIME-012'],
            ['area' => 'secrets', 'pattern' => '/_FILE\b|secrets:|secrets\/|password.txt|master_key/', 'target' => 'P28-RUNTIME-004'],
        ];

        $files = [
            ...$this->files('config', 'php'),
            ...$this->files('docker'),
            ...$this->files('.devcontainer'),
            ...$this->existingFiles([
                '.env.example',
                'composer.json',
                'package.json',
                'playwright.config.ts',
            ]),
        ];

        $signals = [];

        foreach ($files as $file) {
            $lines = explode("\n", $this->read($this->root.'/'.$file));

            foreach ($lines as $index => $line) {
                foreach ($patterns as $definition) {
                    if (preg_match($definition['pattern'], $line) !== 1) {
                        continue;
                    }

                    $signals[] = [
                        'area' => $definition['area'],
                        'evidence' => trim($line),
                        'file' => $file,
                        'line' => $index + 1,
                        'target' => $definition['target'],
                    ];
                }
            }
        }

        usort($signals, static function (array $left, array $right): int {
            return [$left['area'], $left['file'], $left['line'], $left['evidence']]
                <=> [$right['area'], $right['file'], $right['line'], $right['evidence']];
        });

        return $signals;
    }

    /**
     * @param  list<string>  $files
     * @return list<array{file: string, line: int, match: string}>
     */
    private function matchesInFiles(array $files, string $pattern): array
    {
        $matches = [];

        foreach ($files as $file) {
            $contents = $this->read($this->root.'/'.$file);
            $lines = explode("\n", $contents);

            foreach ($lines as $index => $line) {
                if (preg_match($pattern, $line, $match) !== 1) {
                    continue;
                }

                $matches[] = [
                    'file' => $file,
                    'line' => $index + 1,
                    'match' => $match[1] ?? trim($match[0]),
                ];
            }
        }

        return $matches;
    }

    /**
     * @param  list<string>  $roots
     * @return list<string>
     */
    private function matchingFiles(array $roots, string $pattern): array
    {
        $matches = [];

        foreach ($roots as $root) {
            foreach ($this->files($root) as $file) {
                if (preg_match($pattern, $file) === 1) {
                    $matches[] = $file;
                }
            }
        }

        sort($matches);

        return $matches;
    }

    private function firstFile(string $root, string $pattern): ?string
    {
        foreach ($this->files($this->relative($root), 'php') as $file) {
            if (preg_match($pattern, $file) === 1) {
                return $this->root.'/'.$file;
            }
        }

        return null;
    }

    /**
     * @param  list<string>  $files
     * @return list<string>
     */
    private function existingFiles(array $files): array
    {
        return array_values(array_filter(
            $files,
            fn (string $file): bool => is_file($this->root.'/'.$file),
        ));
    }

    private function matchString(string $contents, string $pattern): ?string
    {
        if (preg_match($pattern, $contents, $match) !== 1) {
            return null;
        }

        return $match[1];
    }

    /**
     * @return list<string>
     */
    private function files(string $root, string ...$extensions): array
    {
        $absoluteRoot = $this->root.'/'.$root;

        if (! file_exists($absoluteRoot)) {
            return [];
        }

        $files = [];
        $extensionMap = array_fill_keys($extensions, true);
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($absoluteRoot, FilesystemIterator::SKIP_DOTS));

        foreach ($iterator as $candidate) {
            if (! $candidate instanceof SplFileInfo || ! $candidate->isFile()) {
                continue;
            }

            $path = $candidate->getPathname();

            if (str_contains($path, '/vendor/') || str_contains($path, '/node_modules/') || str_contains($path, '/.git/')) {
                continue;
            }

            if ($extensionMap !== []) {
                $extension = $candidate->getExtension();
                $basename = $candidate->getBasename();

                if (! isset($extensionMap[$extension]) && ! isset($extensionMap[$basename])) {
                    continue;
                }
            }

            $files[] = $this->relative($path);
        }

        sort($files);

        return $files;
    }

    private function read(string $path): string
    {
        $contents = file_get_contents($path);

        if (! is_string($contents)) {
            throw new RuntimeException(sprintf('Unable to read [%s].', $path));
        }

        return $contents;
    }

    private function relative(string $path): string
    {
        return ltrim(str_replace($this->root, '', $path), '/');
    }

    private function listCell(mixed $items): string
    {
        if (! is_array($items) || $items === []) {
            return 'none';
        }

        return implode(', ', array_map(fn (mixed $item): string => $this->markdownInlineCode((string) $item), $items));
    }

    private function markdownInlineCode(string $value): string
    {
        return '`'.$this->markdownCodeText($value).'`';
    }

    private function markdownCodeText(string $value): string
    {
        return str_replace(['`', '|'], ["'", '\\|'], $value);
    }

    private function stringValue(mixed $value): string
    {
        return is_scalar($value) ? (string) $value : '';
    }
}

