    /**
     * @return list<array{owner: string, type: string, value: string, file: string, line: int, target: string}>
     */
    private function auditMatrixSignals(): array
    {
        $signals = [];
        $files = [
            ...$this->phpFiles,
            ...$this->files('database/seeders', 'php'),
        ];

        foreach ($files as $file) {
            $lines = explode("\n", $this->read($this->root.'/'.$file));
            $owner = $this->ownerForPath($file);

            foreach ($lines as $index => $line) {
                if (preg_match('/use App\\\\Modules\\\\Core\\\\Audit\\\\Application\\\\Public\\\\Contracts\\\\AuditRecorder;/', $line) === 1) {
                    $signals[] = $this->auditSignal($owner, 'recorder_contract', 'AuditRecorder', $file, $index + 1);
                }

                if (preg_match('/use App\\\\Modules\\\\Core\\\\Identity\\\\Application\\\\Public\\\\Contracts\\\\SecurityAuditRecorder;/', $line) === 1) {
                    $signals[] = $this->auditSignal($owner, 'recorder_contract', 'SecurityAuditRecorder', $file, $index + 1);
                }

                if (preg_match('/new\s+(AuditEvent|SecurityAuditEvent)\s*\(/', $line, $match) === 1) {
                    $signals[] = $this->auditSignal($owner, 'event_constructor', $match[1], $file, $index + 1);
                }

                foreach (['action', 'result', 'source'] as $argument) {
                    $value = $this->namedArgumentValue($line, $argument);

                    if ($value === null) {
                        continue;
                    }

                    $signals[] = $this->auditSignal($owner, $argument, $value, $file, $index + 1);
                }
            }
        }

        usort($signals, static function (array $left, array $right): int {
            return [$left['owner'], $left['type'], $left['file'], $left['line'], $left['value']]
                <=> [$right['owner'], $right['type'], $right['file'], $right['line'], $right['value']];
        });

        return $signals;
    }

