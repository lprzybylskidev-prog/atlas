#!/usr/bin/env php
<?php

declare(strict_types=1);

final class Phase28InventoryGenerator
{
    private string $root;

    /**
     * @var list<string>
     */
    private array $phpFiles = [];

    /**
     * @var list<string>
     */
    private array $vuePages = [];

    public function __construct(string $root)
    {
        $this->root = rtrim($root, '/');
        $this->phpFiles = $this->files('app', 'php');
        $this->vuePages = $this->files('resources/js/Pages', 'vue');
    }

    /**
     * @return array<string, mixed>
     */
    public function inventory(): array
    {
        return [
            'generated_at' => gmdate('Y-m-d\TH:i:s\Z'),
            'totals' => $this->totals(),
            'modules' => $this->modules(),
            'orphan_module_roots' => $this->orphanModuleRoots(),
            'architecture' => $this->architecture(),
            'routes' => $this->routes(),
            'frontend' => $this->frontend(),
            'migrations' => $this->migrations(),
            'audit' => $this->audit(),
            'mail' => $this->mail(),
            'seeders' => $this->seeders(),
            'runtime' => $this->runtime(),
        ];
    }

    public function json(): string
    {
        $json = json_encode($this->inventory(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);

        if (! is_string($json)) {
            throw new RuntimeException('Unable to encode Phase 28 inventory as JSON.');
        }

        return $json.PHP_EOL;
    }

    public function markdown(): string
    {
        $inventory = $this->inventory();
        $totals = $inventory['totals'];

        if (! is_array($totals)) {
            throw new RuntimeException('Phase 28 inventory totals are invalid.');
        }

        $lines = [
            '# Phase 28 generated inventory',
            '',
            '> Generated by `php tools/phase28/generate-inventory.php --markdown`.',
            '',
            '## Totals',
            '',
            '| Area | Count |',
            '| --- | ---: |',
        ];

        foreach ($totals as $key => $value) {
            $lines[] = sprintf('| `%s` | %s |', $key, (string) $value);
        }

        $lines[] = '';
        $lines[] = '## Modules';
        $lines[] = '';
        $lines[] = '| Module | Category | Required | Optional | Provider | Public files | Public persistence | Actual imports |';
        $lines[] = '| --- | --- | --- | --- | --- | ---: | ---: | --- |';

        foreach ($inventory['modules'] as $module) {
            if (! is_array($module)) {
                continue;
            }

            $lines[] = sprintf(
                '| `%s` | `%s` | %s | %s | `%s` | %d | %d | %s |',
                (string) $module['key'],
                (string) $module['category'],
                $this->listCell($module['required_dependencies']),
                $this->listCell($module['optional_dependencies']),
                (string) $module['provider'],
                (int) $module['public_file_count'],
                (int) $module['public_persistence_file_count'],
                $this->listCell($module['actual_module_imports']),
            );
        }

        $routes = $inventory['routes'];
        if (! is_array($routes)) {
            throw new RuntimeException('Phase 28 route inventory is invalid.');
        }

        $lines[] = '';
        $lines[] = '## Route Prefixes';
        $lines[] = '';
        $lines[] = 'Static parser counts only literal route names in repository route files. Use `php artisan route:list --json` when framework-resolved names are required.';
        $lines[] = '';
        $lines[] = '| Prefix | Count |';
        $lines[] = '| --- | ---: |';
        foreach ($routes['app_owned_prefix_counts'] as $prefix => $count) {
            $lines[] = sprintf('| `%s` | %d |', (string) $prefix, (int) $count);
        }

        $migrations = $inventory['migrations'];
        if (! is_array($migrations)) {
            throw new RuntimeException('Phase 28 migration inventory is invalid.');
        }

        $lines[] = '';
        $lines[] = '## Migration Signals';
        $lines[] = '';
        $lines[] = '| Signal | Count |';
        $lines[] = '| --- | ---: |';
        $lines[] = sprintf('| Schema create/table operations | %d |', count($migrations['schema_operations']));
        $lines[] = sprintf('| PostgreSQL `after` usages | %d |', count($migrations['after_usages']));

        $lines[] = '';
        $lines[] = '## High-Signal Findings';
        $lines[] = '';
        $findings = [
            'public persistence classes' => 'public_persistence_class_count',
            'public persistence uses in app' => 'public_persistence_use_count',
            'raw frontend fetch calls' => 'raw_fetch_count',
            'hardcoded or raw mail signals' => 'mail_signal_count',
            'seeder direct-write signals' => 'seeder_signal_count',
            'runtime drift signals' => 'runtime_signal_count',
            'backend surface signals' => 'backend_surface_signal_count',
            'audit matrix signals' => 'audit_matrix_signal_count',
            'global provider/middleware module imports' => 'global_module_import_count',
            'migration schema operations' => 'migration_schema_operation_count',
            'migration `after` usages' => 'migration_after_usage_count',
        ];

        foreach ($findings as $label => $key) {
            $lines[] = sprintf('- %s: `%s`', $label, (string) ($totals[$key] ?? '0'));
        }

        return implode(PHP_EOL, $lines).PHP_EOL;
    }

    public function frameworkRoutesMarkdown(): string
    {
        $routes = $this->frameworkRoutes();
        $surfaceCounts = [];

        foreach ($routes as $route) {
            $surface = (string) $route['surface'];
            $surfaceCounts[$surface] = ($surfaceCounts[$surface] ?? 0) + 1;
        }

        ksort($surfaceCounts);

        $lines = [
            '# Phase 28 framework route/view matrix',
            '',
            '> Generated by `php tools/phase28/generate-inventory.php --framework-routes-markdown`.',
            '',
            'This matrix uses `php artisan route:list --json`, so it resolves route names created from PHP constants. It remains a Phase 28 working artifact, not a permanent product contract.',
            '',
            '## Surface Counts',
            '',
            '| Surface | Routes |',
            '| --- | ---: |',
        ];

        foreach ($surfaceCounts as $surface => $count) {
            $lines[] = sprintf('| `%s` | %d |', $surface, $count);
        }

        $lines[] = '';
        $lines[] = '## Routes';
        $lines[] = '';
        $lines[] = '| Surface | Method | URI | Name | Action | Inertia pages |';
        $lines[] = '| --- | --- | --- | --- | --- | --- |';

        foreach ($routes as $route) {
            $lines[] = sprintf(
                '| `%s` | `%s` | `%s` | `%s` | `%s` | %s |',
                (string) $route['surface'],
