export interface DynamicTranslationFamily {
    expression: string;
    keys: readonly string[];
}

function family(expression: string, prefix: string, values: readonly string[]): DynamicTranslationFamily {
    return {
        expression,
        keys: values.map((value) => `${prefix}${value}`),
    };
}

function keysFamily(expression: string, keys: readonly string[]): DynamicTranslationFamily {
    return { expression, keys };
}

function modalActionFamily(expression: string, suffix: 'confirm' | 'description' | 'title'): DynamicTranslationFamily {
    return family(expression, 'modal.action.', [
        `acknowledge.${suffix}`,
        `archive.${suffix}`,
        `deactivate.${suffix}`,
        `delete.${suffix}`,
        `rescan.${suffix}`,
        `retry.${suffix}`,
        `revoke.${suffix}`,
    ]);
}

